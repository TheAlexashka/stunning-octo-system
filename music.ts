function profile(firstReply: string): DialogueProfile {
  return { agreesImmediately: true, firstReply, reassurance: '', reassuredReply: '', reassured: true, firmReply: '', persuadedByRules: true };
}

export function useHairConversation(
  visitorId: number,
  bodyHair: BodyHair,
  paused: boolean,
  initial?: ConversationSnapshot,
  disabled = false,
  onReply?: (text: string) => void,
  gender: Gender = 'm',
  hasScales = false,
  scaleStory: ScaleStory = 'other',
  specialCharacter?: 'goebbels',
) {
  const scalePrompt = 'Что с кожей? Эти пятна давно появились — врач не говорил, что это экзема?';
  const hairPrompt = bodyHair === 'long' ? 'Почему у вас такие длинные волосы на теле?'
    : bodyHair === 'stubble' ? 'Вы недавно брили тело? Откуда эта щетина?'
      : 'Вы недавно брили кожу на руках?';
  const isGoebbels = specialCharacter === 'goebbels';
  const profiles = isGoebbels ? GOEBBELS_SKIN_REPLIES.map(profile)
    : hasScales ? SCALE_ANSWERS[scaleStory].map(profile) : PROFILES[bodyHair];
  return useConversation({
    visitorId,
    paused,
    subject: isGoebbels ? 'goebbels-skin' : hasScales ? `scales-${scaleStory}` : `hair-${bodyHair}`,
    profiles,
    prompt: isGoebbels ? 'Что с вашей кожей?' : hasScales ? scalePrompt : hairPrompt,
    insist: '',
    initial,
    disabled,
    onReply,
    gender,
  });
}
