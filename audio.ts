/** Cosmetic ID-only roll: no creature, outfit, voice or story RNG input. */
export function arrivalPhrase(visitorId: number): string {
  let value = (visitorId ^ 0x41525249) >>> 0;
  value = Math.imul(value ^ (value >>> 16), 0x7feb352d);
  value = Math.imul(value ^ (value >>> 15), 0x846ca68b);
  return ARRIVAL_PHRASES[((value ^ (value >>> 16)) >>> 0) % ARRIVAL_PHRASES.length];
}

// Fingerprints of retired openings (no obsolete German/spoiler text kept in
// the executable). Permit old v1 saves/replayed arrivals to resume safely.
const LEGACY_ARRIVAL_HASHES = new Set([
  0x086f3194,
  0x2ab7abc3,
  0x333adea1,
  0x38f55ae4,
  0x4cd30e01,
  0x5d98668f,
  0x5ecac7fc,
  0x6ab220c8,
  0x71537134,
  0x73a13108,
  0x82562e37,
  0x8c28d1f2,
  0x8d2fc85d,
  0x9dbb5683,
  0xb3b95190,
  0xb4788744,
  0xbf915ac3,
  0xcadc0bcc,
  0xd44809b9,
  0xdc443ce0,
  0xe433d7f1,
  0xf97a3764,
  0xfa6a95bd,
  0xff023f20,
]);
function fingerprint(text: string): number {
  let hash = 0x811c9dc5;
  for (const character of text) hash = Math.imul(hash ^ character.codePointAt(0)!, 0x01000193);
  return hash >>> 0;
}

export function normalizeArrivalSpeech(snapshot: SpeechSnapshot | undefined, opening: string): SpeechSnapshot | undefined {
  if (!snapshot || snapshot.text === opening) return snapshot;
  if (snapshot.serial !== 1 && !LEGACY_ARRIVAL_HASHES.has(fingerprint(snapshot.text))) return snapshot;
  const oldLength = Array.from(snapshot.text).length;
  const newLength = Array.from(opening).length;
  const revealed = oldLength === 0 ? 0 : Math.round(Math.min(1, snapshot.revealed / oldLength) * newLength);
  return { ...snapshot, text: opening, revealed };
}
