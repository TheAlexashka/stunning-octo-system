export const OCCUPATION_REPLY_VARIANTS = 19;
export function occupationReply(kind: 'slip' | 'wrong_docs' | 'forged', context: ReplyContext, variant: number): string {
  const bank = kind === 'slip' ? SLIPS
    : kind === 'wrong_docs'
      ? context.missingDocument === 'passport' ? WRONG_DOCUMENTS_WITHOUT_PASSPORT
        : context.missingDocument === 'visa' ? WRONG_DOCUMENTS_WITHOUT_VISA : WRONG_DOCUMENTS
      : COVER_STORIES;
  // Documents keep their DE/RU labels; spoken job names are Russian only.
  const spokenJob = (job: string) => /\(([^)]+)\)/.exec(job)?.[1] ?? job;
  const spokenContext = { ...context, currentJob: spokenJob(context.currentJob), formerJob: spokenJob(context.formerJob) };
  return genderReply(context.gender, bank[Math.abs(variant) % bank.length](spokenContext));
}
