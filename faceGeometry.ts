/**
 * Шесть укладок по постеру BLOSHKA. Без шляпы на листе видно пять голов;
 * шестая укладка описывает то, что торчит из-под федоры у остальных восьми.
 *
 * Каждая укладка имеет СВОЙ контур и СВОЮ линию роста волос, а не общий
 * шаблон с разными параметрами:
 *   зачёс назад   — круглая линия роста, высокий подъём, пробора нет
 *   Флинн         — глубокий пробор, асимметрия, диагональная волна вверх
 *   Гейбл         — М-образные залысины, плоско, высокий лоб, без волн
 *   Тейлор        — стоячий гребень над одним виском
 *   Грант         — лепесток пряди, опущенный ниже линии роста
 *   под шляпу     — самый низкий силуэт, бачки отдельными поверхностями
 */

export const taper = (x: number, y: number, w: number, h: number, seed: number, angle: number, density = 1): TaperSpec => ({
  x, y, w, h, rows: Math.round(7 * density), cols: Math.round(5 * density), seed, len: 2.6, angle,
});

export const sideTaper = (seed: number, density = 1, top = 66): TaperSpec[] => [
  taper(112, top, 12, 26, seed, 104, density),
  taper(176, top, 12, 26, seed + 40, 76, density),
];

export const wave = (x0: number, y0: number, x1: number, y1: number, amp: number, waves: number, w0: number, w1: number, phase = 0): WaveSpec =>
  ({ x0, y0, x1, y1, amp, waves, w0, w1, phase });

/** Затылок ниже ушей — единственное, что видно из заднего слоя в анфас. */
export function nape(bottom: number, seed: number, density = 1): Surface {
  return {
    d: `M116 60C109 76 111 ${bottom - 13} 120 ${bottom}Q150 ${bottom + 7} 180 ${bottom}C189 ${bottom - 13} 191 76 184 60Z`,
    strands: [
      ...combFan([[119, 63], [114, 82], [122, bottom - 3]], [[150, 59], [148, 82], [150, bottom - 1]], 11),
      ...combFan([[181, 63], [186, 82], [178, bottom - 3]], [[150, 59], [152, 82], [150, bottom - 1]], 11),
    ],
    highlights: [`M124 70C119 84 121 ${bottom - 10} 129 ${bottom - 3}C121 ${bottom - 12} 124 82 129 71Z`],
    shadows: [`M150 62C150 78 150 ${bottom - 8} 150 ${bottom}Q158 ${bottom - 2} 162 ${bottom - 9}C160 80 157 70 156 62Z`],
    taper: [taper(120, bottom - 22, 60, 20, seed, 92, density)],
  };
}

