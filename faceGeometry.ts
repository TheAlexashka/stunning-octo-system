export const MEN_HAIR: MenDesign[] = [
  sweptPompadour, hatTaper,
  flynnSweep, gableReceding, taylorCrest,
  grantForelock,
];

export const MEN_DESIGNS: Readonly<Record<string, MenDesign>> = Object.fromEntries(MEN_HAIR.map((design) => [design.id, design]));

export function hasMenWaves(id: string): boolean {
  const design = MEN_DESIGNS[id];
  return !!design && [...design.front, ...design.back].some((surface) => !!surface.waves?.length);
}

